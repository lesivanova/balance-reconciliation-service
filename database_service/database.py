# Импортируем create_engine - функцию для создания движка базы данных
from sqlalchemy import create_engine

# Импортируем sessionmaker (фабрика сессий) и Session (тип сессии)
# sessionmaker - класс для создания конфигурируемой фабрики сессий
# Session - тип данных для аннотации сессии
from sqlalchemy.orm import sessionmaker, Session

# Импортируем Generator из модуля typing для аннотации типа генератора
# Generator[Session, None, None] означает: генерирует Session, не принимает значений,
# не возвращает значения при завершении (используется для yield-функций)
from typing import Generator


import os

# Формируем URL для подключения к базе данных
# os.environ.get() - читает значение переменной окружения по ключу
# Первый аргумент: имя переменной окружения "DATABASE_URL"
# Второй аргумент: значение по умолчанию, если переменная не найдена
DATABASE_URL = os.environ.get(
    "DATABASE_URL",  # Имя переменной окружения (можно задать при запуске)
    # Значение по умолчанию для локальной разработки в Docker-среде:
    # postgresql:// - протокол
    # postgres:postgres - логин:пароль
    # postgres-db - имя хоста (сервис в docker-compose)
    # 5432 - стандартный порт PostgreSQL
    # balance_db - имя базы данных
    "postgresql://postgres:postgres@postgres-db:5432/balance_db"
)

# Создаём движок (engine) базы данных
# Движок пуллит (управляет пулом) соединений, выполняет подключения
# create_engine парсит URL, определяет диалект БД и создаёт соединения
engine = create_engine(DATABASE_URL)

# Создаём фабрику сессий SessionLocal
# sessionmaker() возвращает класс, который будет создавать сессии при вызове
# Параметры:
# - autocommit=False (рекомендованный режим): отключает автоматический коммит,
#   нужно явно вызывать commit() после изменений
# - autoflush=False: отключает автоматический сброс (flush) изменений в БД,
#   даёт больше контроля над транзакциями
# - bind=engine: привязываем фабрику к нашему движку, чтобы сессии знали,
#   к какой БД подключаться
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)


# Определяем функцию-генератор для получения сессии базы данных
# Generator[Session, None, None] - функция возвращает генератор,
# который yield-ит объект Session, не принимает аргументов и не возвращает значения
def get_db() -> Generator[Session, None, None]:
    """
    Функция-генератор для получения сессии базы данных.
    Используется как dependency в FastAPI для автоматического управления
    жизненным циклом сессии (открытие/закрытие).

    """

    # Создаём новую сессию, вызывая SessionLocal (фабрику)
    # Сессия представляет собой "рабочую область" для операций с БД
    db = SessionLocal()

    # Блок try-finally гарантирует закрытие сессии даже при возникновении ошибок
    try:
        # yield возвращает сессию во внешний код (в FastAPI dependency)
        # Внешний код может выполнять запросы через эту сессию
        # После того как внешний код завершит работу, управление возвращается сюда
        yield db
    finally:
        # Этот блок выполняется в любом случае (и при успехе, и при ошибке)
        # Закрываем сессию, освобождая соединение с БД обратно в пул
        db.close()


# Определяем функцию для инициализации базы данных
# Обычно вызывается при запуске приложения или в отдельном скрипте миграции
def init_db():
    """
    Функция для создания всех таблиц в базе данных согласно определённым моделям.

    """

    # Импортируем Base из модуля models (локальный импорт внутри функции)
    # Base - это декларативный базовый класс, от которого наследуются все модели
    # Все модели определены в файле models.py и зарегистрированы в Base.metadata
    from models import Base

    # Вызываем метод create_all() у metadata (коллекции метаданных Base)
    # create_all проверяет, какие таблицы уже существуют, и создаёт отсутствующие
    # bind=engine - указываем движок, с которым работать
    # В результате в БД будут созданы таблицы для всех унаследованных от Base моделей
    Base.metadata.create_all(bind=engine)
