# Импортируем BaseModel - базовый класс Pydantic для создания моделей данных
# Все схемы наследуются от него и получают автоматическую валидацию,
# сериализацию в JSON, парсинг из словарей и документацию
from pydantic import BaseModel

# Импортируем типы данных из модуля typing:
# - List: список элементов определённого типа
# - Optional: поле может быть указанного типа или None
# - Dict: словарь с ключами и значениями определённых типов
# - Any: любой тип (для гибких структур данных)
from typing import List, Optional, Dict, Any

# Импортируем datetime для работы с датой и временем
# Используется в response-моделях для отображения временных меток
from datetime import datetime


# Определяем базовую схему для потока (используется при создании модели)
class FlowBase(BaseModel):
    """
    Базовая Pydantic-модель для описания потока.
    Содержит все необходимые поля для определения потока в технологической схеме.
    Используется при создании новой модели установки.
    """

    # Уникальный идентификатор потока (например, "F001", "steam_line_1")
    # Обязательное поле типа str
    id: str

    # Название/описание потока (например, "Пар высокого давления", "Электроэнергия")
    # Обязательное поле
    name: str

    # Измеренное значение потока (вещественное число)
    # Обязательное поле
    measured_value: float

    # Допуск (погрешность) измерения (вещественное число)
    # Определяет доверие к измерению: чем меньше значение, тем выше доверие
    # Обязательное поле
    tolerance: float

    # Минимально допустимое значение потока
    # По умолчанию 0 (поток не может быть отрицательным)
    # Опциональное поле с заданным значением по умолчанию
    min_value: float = 0

    # Максимально допустимое значение потока
    # По умолчанию 10000 (защита от бесконечных значений)
    # Опциональное поле с заданным значением по умолчанию
    max_value: float = 10000


# Определяем базовую схему для члена уравнения баланса
class EquationTermBase(BaseModel):
    """
    Pydantic-модель для одного члена в уравнении баланса узла.
    Уравнение имеет вид: Σ(sign_i * flow_i) = 0
    """

    # Идентификатор потока, который участвует в уравнении
    # Обязательное поле
    flow_id: str

    # Знак (+1 или -1), определяющий направление потока относительно узла
    # +1 - поток входит в узел
    # -1 - поток выходит из узла
    # Обязательное поле, тип int (целое число)
    sign: int


# Определяем базовую схему для узла балансовой сети
class NodeBase(BaseModel):
    """
    Pydantic-модель для описания узла (вершины) технологической сети.
    Узел может быть смесителем, разделителем, реактором и т.д.
    """

    # Уникальный идентификатор узла (например, "N001", "mixer_1")
    # Обязательное поле
    id: str

    # Название/описание узла (например, "Смеситель №1", "Реактор")
    # Обязательное поле
    name: str

    # Список членов уравнения баланса для этого узла
    # Каждый член - это объект EquationTermBase
    # Обязательное поле, тип - список объектов EquationTermBase
    equations: List[EquationTermBase]


# Определяем схему для создания новой модели установки (запрос от клиента)
class PlantModelCreate(BaseModel):
    """
    Pydantic-модель для создания новой модели технологической установки.
    Используется в POST-запросе к /api/plant-models.
    Не содержит id, version, created_at - эти поля генерируются сервером.
    """

    # Название модели установки (например, "Нефтеперерабатывающий завод")
    # Обязательное поле
    name: str

    # Описание модели (необязательное поле)
    # Optional[str] означает, что поле может быть строкой или None
    # None - значение по умолчанию, если поле не передано
    description: Optional[str] = None

    # Список потоков, определяющих структуру установки
    # Каждый поток - объект FlowBase
    # Обязательное поле
    flows: List[FlowBase]

    # Список узлов с уравнениями баланса
    # Каждый узел - объект NodeBase
    # Обязательное поле
    nodes: List[NodeBase]

    # Список дополнительных линейных ограничений
    # Optional[List[Dict]] - поле может быть None или списком словарей
    # [] - значение по умолчанию (пустой список)
    # Dict без указания типов ключей/значений - гибкая структура
    constraints: Optional[List[Dict]] = []


# Определяем схему для ответа при получении модели установки
class PlantModelResponse(BaseModel):
    """
    Pydantic-модель для ответа сервера с данными модели установки.
    Используется в GET-запросах к /api/plant-models.
    Содержит все поля модели, включая сгенерированные сервером.
    """

    # Уникальный идентификатор модели (генерируется БД при создании)
    # Тип int - автоинкрементный первичный ключ
    id: int

    # Название модели (копируется из запроса)
    name: str

    # Описание модели (может быть None, если не указано)
    # Optional[str] - поле может отсутствовать в ответе или быть None
    description: Optional[str]

    # Версия модели (по умолчанию 1, увеличивается при обновлениях)
    version: int

    # Дата и время создания модели (генерируется сервером)
    # datetime - тип для хранения даты и времени
    created_at: datetime

    # Список потоков модели (те же данные, что и в запросе)
    flows: List[FlowBase]

    # Список узлов модели (те же данные, что и в запросе)
    nodes: List[NodeBase]

    # Список дополнительных ограничений
    # List[Dict] - список словарей произвольной структуры
    constraints: List[Dict]


# Определяем схему для создания новых измерений (запрос от клиента)
class MeasurementDataCreate(BaseModel):
    """
    Pydantic-модель для создания записи с измерениями потоков.
    Используется в POST-запросе к /api/measurements/{model_id}.
    Содержит данные измерений без привязки к конкретным потокам.
    """

    # Название периода измерений (например, "2024-01-15", "смена А", "январь")
    # Обязательное поле, тип str
    period_name: str

    # Описание периода (необязательное поле)
    # Может содержать дополнительную информацию о периоде измерений
    description: Optional[str] = None

    # Список измерений для различных потоков
    # List[Dict[str, Any]] - список словарей, где:
    #   - ключ - строка (обычно "flow_id" и "value")
    #   - значение - любой тип (обычно str для ID и float для значения)
    # Пример: [{"flow_id": "F1", "value": 100.5}, {"flow_id": "F2", "value": 95.2}]
    measurements: List[Dict[str, Any]]


# Определяем схему для ответа с данными измерений
class MeasurementDataResponse(BaseModel):
    """
    Pydantic-модель для ответа сервера с данными измерений.
    Используется в GET-запросах к /api/measurements.
    Содержит все поля измерения, включая сгенерированные сервером.
    """

    # Уникальный идентификатор записи измерений (генерируется БД)
    id: int

    # Идентификатор модели установки, к которой относятся измерения
    # Внешний ключ на таблицу plant_models
    plant_model_id: int

    # Название периода (копируется из запроса)
    period_name: str

    # Описание периода (может быть None)
    description: Optional[str]

    # Временная метка создания записи (генерируется сервером)
    timestamp: datetime

    # Список измерений (копируется из запроса)
    measurements: List[Dict[str, Any]]


# Определяем схему для запроса на выполнение балансировки
class ReconcileRequest(BaseModel):
    """
    Pydantic-модель для запроса на балансировку с использованием
    сохранённых в базе данных модели и измерений.
    Используется в POST-запросе к /api/reconcile.
    """

    # Идентификатор модели установки в базе данных
    # Сервер загрузит структуру модели по этому ID
    plant_model_id: int

    # Название периода измерений
    # Сервер найдёт измерения для этой модели и периода
    period_name: str