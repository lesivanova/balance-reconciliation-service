# Импортируем BaseModel - базовый класс Pydantic для создания моделей данных
# Все схемы наследуются от него и получают автоматическую валидацию,
# сериализацию в JSON, парсинг из словарей и многое другое
from pydantic import BaseModel

# Импортируем типы List (список) и Optional (опциональное значение) из модуля typing
# List используется для аннотации полей, содержащих списки объектов
# Optional означает, что поле может быть либо указанного типа, либо None
from typing import List, Optional


# Определяем схему (модель) для входных данных одного потока
class FlowInput(BaseModel):
    """
    Модель для описания одного потока (трубопровод, линия электропередачи,
    материальный поток и т.д.) с его измеренным значением и допуском
    """

    # Уникальный идентификатор потока (строка)
    # Обязательное поле - должно присутствовать в запросе
    id: str

    # Название/описание потока (например, "Поток_1", "Линия 220 кВ")
    # Обязательное поле
    name: str

    # Измеренное значение потока (вещественное число)
    # Обязательное поле
    measured_value: float

    # Допуск (погрешность) измерения (вещественное число)
    # Определяет, насколько мы доверяем измерению:
    # чем меньше допуск, тем больше вес при балансировке
    # Обязательное поле
    tolerance: float

    # Минимально допустимое значение потока (по умолчанию 0)
    # Неотрицательное число - потоки не могут быть отрицательными
    # Опциональное поле: если не указано, используется 0
    min_value: float = 0

    # Максимально допустимое значение потока (по умолчанию 10000)
    # Опциональное поле: если не указано, используется 10000
    max_value: float = 10000


# Определяем схему для одного члена уравнения баланса узла
class EquationTerm(BaseModel):
    """
    Модель для описания одного слагаемого в уравнении баланса узла
    Уравнение узла: Σ(sign_i * flow_i) = 0
    Например: +Поток1 - Поток2 + Поток3 = 0
    """

    # Идентификатор потока, который входит в уравнение
    # Обязательное поле
    flow_id: str

    # Знак (+1 или -1), с которым поток входит в уравнение
    # +1 - поток входит в узел
    # -1 - поток выходит из узла
    # Обязательное поле, тип int (целое число)
    sign: int


# Определяем схему для узла балансовой сети
class NodeInput(BaseModel):
    """
    Модель для описания узла (вершины графа), где сходятся несколько потоков
    Например: смеситель, распределительное устройство, электрический узел
    """

    # Уникальный идентификатор узла (строка)
    # Обязательное поле
    id: str

    # Название/описание узла (например, "Узел 1", "Подстанция А")
    # Обязательное поле
    name: str

    # Список членов уравнения баланса для этого узла
    # Каждый член - это пара {flow_id: sign}
    # Обязательное поле, тип - список объектов EquationTerm
    equations: List[EquationTerm]


# Определяем схему для одного члена дополнительного ограничения
class ConstraintTerm(BaseModel):
    """
    Модель для описания одного члена в дополнительном линейном ограничении
    Дополнительные ограничения имеют вид: Σ(coefficient_i * flow_i) = rhs
    Например: 2*Поток1 + 0.5*Поток2 = 100 (суммарная мощность)
    """

    # Идентификатор потока, входящего в ограничение
    # Обязательное поле
    flow_id: str

    # Коэффициент, с которым поток входит в ограничение (вещественное число)
    # Например: 2.5, -1, 0.3 и т.д.
    # Обязательное поле
    coefficient: float


# Определяем схему для дополнительного ограничения
class ConstraintInput(BaseModel):
    """
    Модель для описания одного дополнительного линейного ограничения
    Позволяет задать любые линейные соотношения между потоками,
    которые должны выполняться после балансировки
    """

    # Список членов ограничения (коэффициент × поток)
    # Каждый член - объект ConstraintTerm
    # Обязательное поле
    terms: List[ConstraintTerm]

    # Правая часть ограничения (вещественное число)
    # По умолчанию равна 0, если не указана
    # Например: для ограничения вида Σ(коэф * поток) = 100, rhs = 100
    rhs: float = 0


# Определяем схему для всего запроса на балансировку
class BalanceRequest(BaseModel):
    """
    Модель входного запроса к API /api/v1/reconcile
    Содержит все данные, необходимые для выполнения балансировки:
    - список потоков
    - список узлов с балансовыми уравнениями
    - опциональные дополнительные ограничения
    """

    # Список потоков, которые нужно сбалансировать
    # Обязательное поле
    flows: List[FlowInput]

    # Список узлов с уравнениями баланса
    # Обязательное поле
    nodes: List[NodeInput]

    # Список дополнительных ограничений (опционально)
    # Optional означает, что поле может отсутствовать в запросе (быть None)
    # Если не указано, используется значение None
    constraints: Optional[List[ConstraintInput]] = None


# Определяем схему для одного сбалансированного потока (в ответе)
class BalancedFlow(BaseModel):
    """
    Модель для представления результата балансировки одного потока
    Используется в ответе API
    """

    # Идентификатор потока (копируется из запроса)
    id: str

    # Название потока (копируется из запроса)
    name: str

    # Исходное измеренное значение (до балансировки)
    original_value: float

    # Сбалансированное значение (после оптимизации)
    balanced_value: float

    # Поправка = balanced_value - original_value
    # Положительная - поток увеличен, отрицательная - уменьшен
    correction: float

    # Относительная погрешность в процентах:
    # |correction| / |original_value| * 100
    # Показывает, насколько сильно изменилось значение относительно измерения
    relative_error: float


# Определяем схему для ответа API на успешную балансировку
class BalanceResponse(BaseModel):
    """
    Модель ответа API /api/v1/reconcile
    Содержит результаты балансировки и статистическую информацию
    """

    # Статус выполнения: "success", "failed", "error"
    # Обязательное поле
    status: str

    # Список сбалансированных потоков с деталями
    # Обязательное поле
    balanced_flows: List[BalancedFlow]

    # Максимальная невязка балансов (должна быть близка к 0 для успешного решения)
    # Обязательное поле
    max_disbalance: float

    # Количество итераций оптимизатора (для оценки сложности задачи)
    # Обязательное поле
    iterations: int

    # Дополнительное сообщение (например, ошибка или предупреждение)
    # Опциональное поле: может быть None
    message: Optional[str] = None

    # Нормированное значение глобального теста (статистика хи-квадрат / критическое значение)
    # Показывает степень согласованности данных:
    # < 1 - данные согласованы с моделью
    # > 1 - есть статистически значимые расхождения
    # Опциональное поле
    global_test: Optional[float] = None

    # Критическое значение хи-квадрат для текущего числа степеней свободы
    # При уровне значимости 5% (alpha=0.05)
    # Опциональное поле
    global_test_limit: Optional[float] = None

    # Исходное значение глобального теста (статистика хи-квадрат)
    # Используется для точных расчётов
    # Опциональное поле
    global_test_original: Optional[float] = None

    # Флаг, указывающий, согласованы ли данные с моделью на уровне значимости 5%
    # True - данные не противоречат модели
    # False - есть значимые расхождения (возможны грубые ошибки)
    # Опциональное поле
    is_consistent: Optional[bool] = None

    # Количество степеней свободы = число ограничений (узлов + доп. ограничений)
    # Важно для интерпретации глобального теста
    # Опциональное поле
    degrees_of_freedom: Optional[int] = None